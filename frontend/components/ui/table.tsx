import * as React from 'react';

import { cn } from '@/lib/utils';

/**
 * Table primitive — no outer scroll wrapper.
 * Use `TableScroll` / `ResponsiveDataTable` from `@/components/ds/responsive-table`
 * for overflow behavior so page roots never become the scroll container.
 */
const Table = React.forwardRef<
  HTMLTableElement,
  React.HTMLAttributes<HTMLTableElement>
>(({ className, ...props }, ref) => (
  <table
    ref={ref}
    className={cn('w-full caption-bottom border-separate border-spacing-0 text-sm', className)}
    {...props}
  />
));
Table.displayName = 'Table';

